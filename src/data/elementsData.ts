export function getAllElements(): ChemicalElement[] {
  const existingMap = new Map<number, ChemicalElement>();
  ELEMENTS_DATA.forEach(el => existingMap.set(el.number, el));

  const completeList: ChemicalElement[] = [];

  for (let num = 1; num <= 118; num++) {
    if (existingMap.has(num)) {
      completeList.push(existingMap.get(num)!);
    } else {
      const sym = ALL_118_SYMBOLS[num - 1] || `E${num}`;
      const fallbackInfo = PERIOD_GROUP_MAP[num] || {
        period: num <= 56 ? 5 : num <= 88 ? 6 : 7,
        group: (num % 18) || 18,
        cat: num >= 57 && num <= 71 ? 'lanthanide' : num >= 89 && num <= 103 ? 'actinide' : 'transition',
        catUz: num >= 57 && num <= 71 ? 'Lantanoid' : num >= 89 && num <= 103 ? 'Aktinoid' : 'O‘tish metalli',
        mass: Math.round(num * 2.45),
        name: sym,
        phase: 'Qattiq'
      };

      completeList.push({
        number: num,
        symbol: sym,
        name: fallbackInfo.name || sym,
        latinName: sym,
        atomicMass: fallbackInfo.mass,
        period: fallbackInfo.period,
        group: fallbackInfo.group,
        category: fallbackInfo.cat,
        categoryNameUz: fallbackInfo.catUz,
        electronConfig: `[Element ${num}]`,
        electronegativity: undefined,
        density: undefined,
        phase: fallbackInfo.phase,
        summaryUz: `${fallbackInfo.name || sym} — Mendeleyev davriy jadvalidagi ${num}-tartib raqamli kimyoviy element.`,
        usesUz: ["Ilmiy tadqiqotlar", "Sanoat sintezlari"],
        valence: "O‘zgaruvchan"
      });
    }
  }

  return completeList;
}

